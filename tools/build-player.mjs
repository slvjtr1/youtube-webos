import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const cwd = fileURLToPath(new URL('../', import.meta.url));
const scratch = mkdtempSync(join(tmpdir(), 'webos-player-'));
const wasm = join(scratch, 'player.wasm');
const legacy = join(scratch, 'legacy.js');
try {
  const flags = [
    '-Oz',
    '-std=c11',
    '-fvisibility=default',
    '-ffreestanding',
    '-nostdlib',
    '-mcpu=mvp',
    'native/settings.c',
    'native/timeline.c',
    'native/policy.c',
    'native/urls.c',
    'native/hash.c',
    'native/response.c',
    '-Wl,--no-entry',
    '-Wl,--export-dynamic',
    '-Wl,--strip-all',
    '-Wl,-z,stack-size=16384',
    '-o',
    wasm
  ];
  execFileSync(
    process.env.ZIG || process.env.CLANG || 'clang',
    process.env.ZIG
      ? ['cc', '-target', 'wasm32-freestanding', ...flags]
      : ['--target=wasm32', ...flags],
    { cwd, stdio: 'inherit' }
  );
  const wasm2js = process.env.WASM2JS;
  if (wasm2js)
    execFileSync(
      process.execPath,
      [wasm2js, wasm, '--emscripten', '-O', '-o', legacy],
      { stdio: 'inherit' }
    );
  else
    execFileSync('wasm2js', [wasm, '--emscripten', '-O', '-o', legacy], {
      stdio: 'inherit'
    });
  writeFileSync(join(cwd, 'native/player.wasm'), readFileSync(wasm));
  writeFileSync(
    join(cwd, 'native/player-legacy.js'),
    '/* Generated by Binaryen wasm2js from the C player sources. */\n' +
      readFileSync(legacy, 'utf8').replace(/[^\S\r\n]+$/gm, '') +
      '\nexport default instantiate;\n'
  );
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
